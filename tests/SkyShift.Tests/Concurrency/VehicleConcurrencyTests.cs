using Microsoft.EntityFrameworkCore;
using SkyShift.Domain.Entities;
using SkyShift.Infrastructure.Persistence;
using Xunit;

namespace SkyShift.Tests.Concurrency;

/// <summary>
/// The specific, separately-required proof from the course spec: two
/// independent DbContext instances read the same entity, both modify it,
/// the first SaveChangesAsync succeeds, and the second throws
/// DbUpdateConcurrencyException. This exercises the real, already-approved
/// optimistic-concurrency token on Vehicle (the shadow "RowVersion"
/// property, configured via .IsRowVersion() in VehicleConfiguration) --
/// nothing about that configuration, or about UnitOfWork's translation of
/// this exception into VehicleNotAvailableException/409, is touched here.
///
/// Uses EF Core's InMemory provider rather than the production SqlServer
/// provider, purely so this test needs no real database connection.
/// InMemory has no equivalent of SQL Server's native "rowversion" column,
/// which the database engine itself regenerates on every UPDATE -- so,
/// unlike against the real SqlServer provider, the RowVersion value would
/// never actually change between the two saves below, and no conflict
/// would ever be detected. The single explicit RowVersion write before
/// context1's save (see below) stands in for that server-side behavior;
/// everything this test is actually meant to prove -- two contexts reading
/// the same row, the first save succeeding, the second save's now-stale
/// original value being rejected -- is exercised exactly as it would be
/// against SQL Server.
/// </summary>
public class VehicleConcurrencyTests
{
    [Fact]
    public async Task TwoContextsRacingOnSameVehicle_FirstSaveSucceeds_SecondThrowsConcurrencyException()
    {
        var dbName = Guid.NewGuid().ToString();
        var options = new DbContextOptionsBuilder<SkyShiftDbContext>()
            .UseInMemoryDatabase(dbName)
            .Options;

        int vehicleId;
        await using (var seedContext = new SkyShiftDbContext(options))
        {
            var vehicle = Vehicle.Create(isPersonalExperimental: false, createdAt: DateTime.UtcNow);
            seedContext.Vehicles.Add(vehicle);
            await seedContext.SaveChangesAsync();
            vehicleId = vehicle.Id;
        }

        // Two independent DbContexts -- standing in for two concurrent
        // requests/users -- load the SAME row.
        await using var context1 = new SkyShiftDbContext(options);
        await using var context2 = new SkyShiftDbContext(options);

        var vehicle1 = await context1.Vehicles.FirstAsync(v => v.Id == vehicleId);
        var vehicle2 = await context2.Vehicles.FirstAsync(v => v.Id == vehicleId);

        // Both mutate their own in-memory copy. Neither has seen the
        // other's change yet -- exactly the race window the spec
        // describes -- so both pass the in-memory Domain check in
        // Vehicle.Assign() and reach SaveChanges.
        vehicle1.Assign();
        vehicle2.Assign();

        // Against the real SqlServer provider, the "RowVersion" column is
        // regenerated by the database engine itself on every UPDATE -- no
        // EF Core or application code makes that happen. The InMemory
        // provider has no database engine underneath it, so nothing
        // regenerates the value automatically; without this line the
        // stored RowVersion would never change and the second save below
        // would incorrectly succeed. This one explicit write is the
        // InMemory-only stand-in for that server-side behavior -- it does
        // not change what is being proven: context2 is still working from
        // the RowVersion value it originally read, which no longer matches
        // what is now stored.
        context1.Entry(vehicle1).Property("RowVersion").CurrentValue = Guid.NewGuid().ToByteArray();

        // First save wins.
        await context1.SaveChangesAsync();

        // Second save is working from a now-stale RowVersion: EF Core
        // includes the original token value in the update, finds no
        // matching row, and throws. In the real application pipeline this
        // exact exception is what UnitOfWork.SaveChangesAsync catches and
        // translates into VehicleNotAvailableException -> 409 -- untouched
        // by this test.
        await Assert.ThrowsAsync<DbUpdateConcurrencyException>(() => context2.SaveChangesAsync());
    }
}
